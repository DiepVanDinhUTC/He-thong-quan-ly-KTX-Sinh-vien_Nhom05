ALTER TABLE "STUDENT_FEEDBACK"
ADD COLUMN IF NOT EXISTS "maToaNha" VARCHAR(20);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'STUDENT_FEEDBACK_maToaNha_fkey'
    ) THEN
        ALTER TABLE "STUDENT_FEEDBACK"
        ADD CONSTRAINT "STUDENT_FEEDBACK_maToaNha_fkey"
        FOREIGN KEY ("maToaNha") REFERENCES "TOA_NHA"("maToaNha")
        ON DELETE NO ACTION ON UPDATE NO ACTION;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS "STUDENT_FEEDBACK_maToaNha_createdAt_idx"
ON "STUDENT_FEEDBACK"("maToaNha", "createdAt");
