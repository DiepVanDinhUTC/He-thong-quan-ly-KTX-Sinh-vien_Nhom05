CREATE TABLE IF NOT EXISTS "STUDENT_BILL_NOTIFICATION" (
    "id" VARCHAR(36) NOT NULL,
    "maSinhVien" VARCHAR(20) NOT NULL,
    "invoiceType" VARCHAR(20) NOT NULL,
    "invoiceId" VARCHAR(36) NOT NULL,
    "kind" VARCHAR(16) NOT NULL,
    "dedupeKey" VARCHAR(120) NOT NULL,
    "title" VARCHAR(160) NOT NULL,
    "message" VARCHAR(500) NOT NULL,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "readAt" TIMESTAMP(3),
    "resolvedAt" TIMESTAMP(3),
    CONSTRAINT "STUDENT_BILL_NOTIFICATION_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "STUDENT_BILL_NOTIFICATION_maSinhVien_fkey"
        FOREIGN KEY ("maSinhVien") REFERENCES "SINH_VIEN"("maSV") ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE UNIQUE INDEX IF NOT EXISTS "STUDENT_BILL_NOTIFICATION_student_dedupe_key"
    ON "STUDENT_BILL_NOTIFICATION" ("maSinhVien", "dedupeKey");
CREATE INDEX IF NOT EXISTS "STUDENT_BILL_NOTIFICATION_maSinhVien_resolvedAt_createdAt_idx"
    ON "STUDENT_BILL_NOTIFICATION" ("maSinhVien", "resolvedAt", "createdAt");
CREATE INDEX IF NOT EXISTS "STUDENT_BILL_NOTIFICATION_invoiceType_invoiceId_idx"
    ON "STUDENT_BILL_NOTIFICATION" ("invoiceType", "invoiceId");
