CREATE TABLE "FINANCIAL_TRANSACTION" (
    "id" VARCHAR(36) NOT NULL,
    "transactionType" VARCHAR(24) NOT NULL,
    "amount" INTEGER NOT NULL,
    "method" VARCHAR(20) NOT NULL,
    "status" VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
    "invoiceType" VARCHAR(20),
    "invoiceId" VARCHAR(36),
    "maSinhVien" VARCHAR(20),
    "maToaNha" VARCHAR(20),
    "ticketId" VARCHAR(36),
    "bankReference" VARCHAR(100),
    "paymentReference" VARCHAR(100),
    "description" VARCHAR(1000),
    "reviewNote" VARCHAR(500),
    "createdById" TEXT,
    "reviewedById" TEXT,
    "reviewedAt" TIMESTAMP(3),
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "FINANCIAL_TRANSACTION_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "FINANCIAL_TRANSACTION_amount_check" CHECK ("amount" > 0),
    CONSTRAINT "FINANCIAL_TRANSACTION_type_check" CHECK ("transactionType" IN ('COLLECTION', 'REFUND', 'REPAIR_EXPENSE')),
    CONSTRAINT "FINANCIAL_TRANSACTION_status_check" CHECK ("status" IN ('CONFIRMED', 'NEEDS_REVIEW')),
    CONSTRAINT "FINANCIAL_TRANSACTION_maSinhVien_fkey" FOREIGN KEY ("maSinhVien") REFERENCES "SINH_VIEN"("maSV") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "FINANCIAL_TRANSACTION_maToaNha_fkey" FOREIGN KEY ("maToaNha") REFERENCES "TOA_NHA"("maToaNha") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "FINANCIAL_TRANSACTION_ticketId_fkey" FOREIGN KEY ("ticketId") REFERENCES "MAINTENANCE_TICKET"("id") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "FINANCIAL_TRANSACTION_createdById_fkey" FOREIGN KEY ("createdById") REFERENCES "USER_ACCOUNT"("id") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "FINANCIAL_TRANSACTION_reviewedById_fkey" FOREIGN KEY ("reviewedById") REFERENCES "USER_ACCOUNT"("id") ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE UNIQUE INDEX "FINANCIAL_TRANSACTION_paymentReference_key" ON "FINANCIAL_TRANSACTION"("paymentReference");
CREATE INDEX "FINANCIAL_TRANSACTION_createdAt_transactionType_idx" ON "FINANCIAL_TRANSACTION"("createdAt", "transactionType");
CREATE INDEX "FINANCIAL_TRANSACTION_maToaNha_createdAt_idx" ON "FINANCIAL_TRANSACTION"("maToaNha", "createdAt");
CREATE INDEX "FINANCIAL_TRANSACTION_status_createdAt_idx" ON "FINANCIAL_TRANSACTION"("status", "createdAt");
CREATE INDEX "FINANCIAL_TRANSACTION_invoiceType_invoiceId_transactionType_idx" ON "FINANCIAL_TRANSACTION"("invoiceType", "invoiceId", "transactionType");
CREATE INDEX "FINANCIAL_TRANSACTION_bankReference_idx" ON "FINANCIAL_TRANSACTION"("bankReference");
CREATE INDEX "FINANCIAL_TRANSACTION_ticketId_transactionType_idx" ON "FINANCIAL_TRANSACTION"("ticketId", "transactionType");
CREATE UNIQUE INDEX "FINANCIAL_TRANSACTION_ticket_type_key" ON "FINANCIAL_TRANSACTION"("ticketId", "transactionType");
