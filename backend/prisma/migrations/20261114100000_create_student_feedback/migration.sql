CREATE TABLE IF NOT EXISTS "STUDENT_FEEDBACK" (
    "id" VARCHAR(36) NOT NULL,
    "maSinhVien" VARCHAR(20) NOT NULL,
    "title" VARCHAR(160) NOT NULL,
    "description" VARCHAR(2000) NOT NULL,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "STUDENT_FEEDBACK_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "STUDENT_FEEDBACK_maSinhVien_fkey" FOREIGN KEY ("maSinhVien") REFERENCES "SINH_VIEN"("maSV") ON DELETE NO ACTION ON UPDATE NO ACTION
);
CREATE INDEX IF NOT EXISTS "STUDENT_FEEDBACK_createdAt_idx" ON "STUDENT_FEEDBACK"("createdAt");
CREATE INDEX IF NOT EXISTS "STUDENT_FEEDBACK_maSinhVien_createdAt_idx" ON "STUDENT_FEEDBACK"("maSinhVien", "createdAt");
