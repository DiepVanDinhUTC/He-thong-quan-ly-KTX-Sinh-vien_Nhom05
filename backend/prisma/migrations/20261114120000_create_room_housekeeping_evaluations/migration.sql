CREATE TABLE "ROOM_HOUSEKEEPING_EVALUATION" (
    "id" VARCHAR(36) NOT NULL,
    "maPhong" TEXT NOT NULL,
    "recordedById" TEXT NOT NULL,
    "generalScore" INTEGER NOT NULL,
    "livingScore" INTEGER NOT NULL,
    "securityScore" INTEGER NOT NULL,
    "propertyScore" INTEGER NOT NULL,
    "environmentScore" INTEGER NOT NULL,
    "notes" VARCHAR(2000),
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "ROOM_HOUSEKEEPING_EVALUATION_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "ROOM_HOUSEKEEPING_EVALUATION_generalScore_check" CHECK ("generalScore" BETWEEN 1 AND 5),
    CONSTRAINT "ROOM_HOUSEKEEPING_EVALUATION_livingScore_check" CHECK ("livingScore" BETWEEN 1 AND 5),
    CONSTRAINT "ROOM_HOUSEKEEPING_EVALUATION_securityScore_check" CHECK ("securityScore" BETWEEN 1 AND 5),
    CONSTRAINT "ROOM_HOUSEKEEPING_EVALUATION_propertyScore_check" CHECK ("propertyScore" BETWEEN 1 AND 5),
    CONSTRAINT "ROOM_HOUSEKEEPING_EVALUATION_environmentScore_check" CHECK ("environmentScore" BETWEEN 1 AND 5),
    CONSTRAINT "ROOM_HOUSEKEEPING_EVALUATION_maPhong_fkey" FOREIGN KEY ("maPhong") REFERENCES "Phong"("maPhong") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "ROOM_HOUSEKEEPING_EVALUATION_recordedById_fkey" FOREIGN KEY ("recordedById") REFERENCES "USER_ACCOUNT"("id") ON DELETE NO ACTION ON UPDATE NO ACTION
);
CREATE INDEX "ROOM_HOUSEKEEPING_EVALUATION_maPhong_createdAt_idx" ON "ROOM_HOUSEKEEPING_EVALUATION"("maPhong", "createdAt");
CREATE INDEX "ROOM_HOUSEKEEPING_EVALUATION_recordedById_createdAt_idx" ON "ROOM_HOUSEKEEPING_EVALUATION"("recordedById", "createdAt");
