CREATE TABLE "MILITARY_NOTIFICATION" (
    "id" VARCHAR(36) NOT NULL,
    "maSinhVien" VARCHAR(20) NOT NULL,
    "bookingId" VARCHAR(36) NOT NULL,
    "title" VARCHAR(160) NOT NULL,
    "message" VARCHAR(500) NOT NULL,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "readAt" TIMESTAMP(3),
    CONSTRAINT "MILITARY_NOTIFICATION_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "MILITARY_NOTIFICATION_maSinhVien_fkey" FOREIGN KEY ("maSinhVien") REFERENCES "SINH_VIEN"("maSV") ON DELETE NO ACTION ON UPDATE NO ACTION
);
CREATE INDEX "MILITARY_NOTIFICATION_maSinhVien_createdAt_idx" ON "MILITARY_NOTIFICATION"("maSinhVien", "createdAt");
CREATE INDEX "MILITARY_NOTIFICATION_bookingId_idx" ON "MILITARY_NOTIFICATION"("bookingId");
