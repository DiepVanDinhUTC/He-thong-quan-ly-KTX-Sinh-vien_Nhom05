ALTER TABLE "MILITARY_ROOM_ASSIGNMENT"
    ADD COLUMN IF NOT EXISTS "startsAt" TIMESTAMP(3),
    ADD COLUMN IF NOT EXISTS "endsAt" TIMESTAMP(3),
    ADD COLUMN IF NOT EXISTS "batchCode" VARCHAR(50);

UPDATE "MILITARY_ROOM_ASSIGNMENT"
SET "startsAt" = COALESCE("startsAt", "assignedAt"),
    "endsAt" = COALESCE("endsAt", "startsAt" + INTERVAL '14 days', "assignedAt" + INTERVAL '14 days')
WHERE "startsAt" IS NULL OR "endsAt" IS NULL;

ALTER TABLE "MILITARY_ROOM_ASSIGNMENT"
    ALTER COLUMN "startsAt" SET NOT NULL,
    ALTER COLUMN "startsAt" SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN "endsAt" SET NOT NULL,
    ALTER COLUMN "endsAt" SET DEFAULT (CURRENT_TIMESTAMP + INTERVAL '14 days');

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'MILITARY_ROOM_ASSIGNMENT_two_week_period_check'
        AND conrelid = '"MILITARY_ROOM_ASSIGNMENT"'::regclass) THEN
        ALTER TABLE "MILITARY_ROOM_ASSIGNMENT" ADD CONSTRAINT "MILITARY_ROOM_ASSIGNMENT_two_week_period_check"
            CHECK ("endsAt" = "startsAt" + INTERVAL '14 days');
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS "MILITARY_ROOM_ASSIGNMENT_status_endsAt_idx"
    ON "MILITARY_ROOM_ASSIGNMENT"("status", "endsAt");
