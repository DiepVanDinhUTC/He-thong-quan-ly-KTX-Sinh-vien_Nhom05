CREATE TABLE IF NOT EXISTS "MONTHLY_INVOICE" (
    "id" VARCHAR(36) NOT NULL,
    "maSinhVien" VARCHAR(20) NOT NULL,
    "maHopDong" TEXT NOT NULL,
    "periodStart" DATE NOT NULL,
    "status" VARCHAR(16) NOT NULL DEFAULT 'UNPAID',
    "totalAmount" INTEGER NOT NULL DEFAULT 0,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,
    CONSTRAINT "MONTHLY_INVOICE_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "MONTHLY_INVOICE_totalAmount_check" CHECK ("totalAmount" >= 0),
    CONSTRAINT "MONTHLY_INVOICE_sinhVien_fkey" FOREIGN KEY ("maSinhVien") REFERENCES "SINH_VIEN"("maSV") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "MONTHLY_INVOICE_hopDong_fkey" FOREIGN KEY ("maHopDong") REFERENCES "HopDong"("maHopDong") ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE UNIQUE INDEX IF NOT EXISTS "MONTHLY_INVOICE_contract_period_key"
    ON "MONTHLY_INVOICE" ("maHopDong", "periodStart");
CREATE INDEX IF NOT EXISTS "MONTHLY_INVOICE_maSinhVien_periodStart_idx"
    ON "MONTHLY_INVOICE" ("maSinhVien", "periodStart");

CREATE TABLE IF NOT EXISTS "MONTHLY_INVOICE_ITEM" (
    "id" VARCHAR(36) NOT NULL,
    "invoiceId" VARCHAR(36) NOT NULL,
    "type" VARCHAR(30) NOT NULL,
    "description" VARCHAR(1000) NOT NULL,
    "amount" INTEGER NOT NULL,
    "ticketId" VARCHAR(36),
    "assessedById" TEXT NOT NULL,
    "assessedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "MONTHLY_INVOICE_ITEM_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "MONTHLY_INVOICE_ITEM_amount_check" CHECK ("amount" > 0),
    CONSTRAINT "MONTHLY_INVOICE_ITEM_invoice_fkey" FOREIGN KEY ("invoiceId") REFERENCES "MONTHLY_INVOICE"("id") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "MONTHLY_INVOICE_ITEM_ticket_fkey" FOREIGN KEY ("ticketId") REFERENCES "MAINTENANCE_TICKET"("id") ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE UNIQUE INDEX IF NOT EXISTS "MONTHLY_INVOICE_ITEM_ticketId_key"
    ON "MONTHLY_INVOICE_ITEM" ("ticketId");
CREATE INDEX IF NOT EXISTS "MONTHLY_INVOICE_ITEM_invoiceId_type_idx"
    ON "MONTHLY_INVOICE_ITEM" ("invoiceId", "type");
