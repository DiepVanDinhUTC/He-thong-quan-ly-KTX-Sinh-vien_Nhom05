/* Student self-service requests for room changes/returns and optional services. */
IF OBJECT_ID(N'dbo.STUDENT_HOUSING_REQUEST', N'U') IS NULL
BEGIN
    CREATE TABLE [dbo].[STUDENT_HOUSING_REQUEST] (
        [id] VARCHAR(36) NOT NULL CONSTRAINT [DF_STUDENT_HOUSING_REQUEST_id] DEFAULT CONVERT(VARCHAR(36), NEWID()),
        [maSinhVien] VARCHAR(20) NOT NULL,
        [maHopDong] NVARCHAR(100) NOT NULL,
        [requestType] VARCHAR(16) NOT NULL,
        [maPhongMoi] NVARCHAR(100) NULL,
        [reason] NVARCHAR(1000) NULL,
        [status] VARCHAR(16) NOT NULL CONSTRAINT [DF_STUDENT_HOUSING_REQUEST_status] DEFAULT 'PENDING',
        [staffNote] NVARCHAR(500) NULL,
        [createdAt] DATETIME2 NOT NULL CONSTRAINT [DF_STUDENT_HOUSING_REQUEST_createdAt] DEFAULT SYSUTCDATETIME(),
        [updatedAt] DATETIME2 NOT NULL CONSTRAINT [DF_STUDENT_HOUSING_REQUEST_updatedAt] DEFAULT SYSUTCDATETIME(),
        [decidedAt] DATETIME2 NULL,
        CONSTRAINT [PK_STUDENT_HOUSING_REQUEST] PRIMARY KEY ([id]),
        CONSTRAINT [FK_STUDENT_HOUSING_REQUEST_SINH_VIEN] FOREIGN KEY ([maSinhVien]) REFERENCES [dbo].[SINH_VIEN]([maSV])
    );
END;

IF OBJECT_ID(N'dbo.STUDENT_SERVICE_REGISTRATION', N'U') IS NULL
BEGIN
    CREATE TABLE [dbo].[STUDENT_SERVICE_REGISTRATION] (
        [id] VARCHAR(36) NOT NULL CONSTRAINT [DF_STUDENT_SERVICE_REGISTRATION_id] DEFAULT CONVERT(VARCHAR(36), NEWID()),
        [maSinhVien] VARCHAR(20) NOT NULL,
        [maHopDong] NVARCHAR(100) NOT NULL,
        [serviceCode] VARCHAR(32) NOT NULL,
        [serviceName] NVARCHAR(100) NOT NULL,
        [status] VARCHAR(16) NOT NULL CONSTRAINT [DF_STUDENT_SERVICE_REGISTRATION_status] DEFAULT 'PENDING',
        [note] NVARCHAR(500) NULL,
        [createdAt] DATETIME2 NOT NULL CONSTRAINT [DF_STUDENT_SERVICE_REGISTRATION_createdAt] DEFAULT SYSUTCDATETIME(),
        [cancelledAt] DATETIME2 NULL,
        CONSTRAINT [PK_STUDENT_SERVICE_REGISTRATION] PRIMARY KEY ([id]),
        CONSTRAINT [FK_STUDENT_SERVICE_REGISTRATION_SINH_VIEN] FOREIGN KEY ([maSinhVien]) REFERENCES [dbo].[SINH_VIEN]([maSV])
    );
END;

