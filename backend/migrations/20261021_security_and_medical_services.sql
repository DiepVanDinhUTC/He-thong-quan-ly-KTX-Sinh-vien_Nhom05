CREATE TABLE IF NOT EXISTS "SECURITY_ACCESS_LOG" (
    "id" VARCHAR(36) NOT NULL,
    "maToaNha" VARCHAR(20) NOT NULL,
    "maSinhVien" VARCHAR(20),
    "maPhong" TEXT,
    "visitorName" VARCHAR(120) NOT NULL,
    "visitorPhone" VARCHAR(20),
    "visitorType" VARCHAR(20) NOT NULL DEFAULT 'GUEST',
    "vehiclePlate" VARCHAR(20),
    "purpose" VARCHAR(500) NOT NULL,
    "note" VARCHAR(500),
    "checkedInAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "checkedOutAt" TIMESTAMP(3),
    "recordedById" TEXT NOT NULL,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "SECURITY_ACCESS_LOG_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "SECURITY_ACCESS_LOG_maToaNha_fkey" FOREIGN KEY ("maToaNha") REFERENCES "TOA_NHA"("maToaNha") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "SECURITY_ACCESS_LOG_maSinhVien_fkey" FOREIGN KEY ("maSinhVien") REFERENCES "SINH_VIEN"("maSV") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "SECURITY_ACCESS_LOG_maPhong_fkey" FOREIGN KEY ("maPhong") REFERENCES "Phong"("maPhong") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "SECURITY_ACCESS_LOG_recordedById_fkey" FOREIGN KEY ("recordedById") REFERENCES "USER_ACCOUNT"("id") ON DELETE NO ACTION ON UPDATE NO ACTION
);
CREATE INDEX IF NOT EXISTS "SECURITY_ACCESS_LOG_maToaNha_checkedInAt_idx" ON "SECURITY_ACCESS_LOG"("maToaNha", "checkedInAt");
CREATE INDEX IF NOT EXISTS "SECURITY_ACCESS_LOG_maSinhVien_checkedInAt_idx" ON "SECURITY_ACCESS_LOG"("maSinhVien", "checkedInAt");
CREATE INDEX IF NOT EXISTS "SECURITY_ACCESS_LOG_checkedOutAt_idx" ON "SECURITY_ACCESS_LOG"("checkedOutAt");

