CREATE TABLE [USER_BUILDING_ACCESS] (
    [userId] NVARCHAR(1000) NOT NULL,
    [maToaNha] VARCHAR(20) NOT NULL,
    [createdAt] DATETIME2 NOT NULL CONSTRAINT [DF_USER_BUILDING_ACCESS_createdAt] DEFAULT CURRENT_TIMESTAMP,
