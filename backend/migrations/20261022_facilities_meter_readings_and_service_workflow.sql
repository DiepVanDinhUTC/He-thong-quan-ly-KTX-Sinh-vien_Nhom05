CREATE TABLE IF NOT EXISTS "UTILITY_METER_READING" (
    "id" VARCHAR(36) NOT NULL,
    "maPhong" TEXT NOT NULL,
    "utilityType" VARCHAR(16) NOT NULL,
    "periodStart" DATE NOT NULL,
    "previousReading" INTEGER NOT NULL,
    "currentReading" INTEGER NOT NULL,
    "memo" VARCHAR(500),
    "recordedById" TEXT NOT NULL,
    "updatedById" TEXT,
    "recordedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "UTILITY_METER_READING_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "UTILITY_METER_READING_room_type_period_key" UNIQUE ("maPhong", "utilityType", "periodStart"),
    CONSTRAINT "UTILITY_METER_READING_utilityType_check" CHECK ("utilityType" IN ('ELECTRICITY', 'WATER')),
    CONSTRAINT "UTILITY_METER_READING_readings_check" CHECK ("previousReading" >= 0 AND "currentReading" >= "previousReading"),
    CONSTRAINT "UTILITY_METER_READING_maPhong_fkey" FOREIGN KEY ("maPhong") REFERENCES "Phong"("maPhong") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "UTILITY_METER_READING_recordedById_fkey" FOREIGN KEY ("recordedById") REFERENCES "USER_ACCOUNT"("id") ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT "UTILITY_METER_READING_updatedById_fkey" FOREIGN KEY ("updatedById") REFERENCES "USER_ACCOUNT"("id") ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE INDEX IF NOT EXISTS "UTILITY_METER_READING_periodStart_utilityType_idx"
    ON "UTILITY_METER_READING"("periodStart", "utilityType");

